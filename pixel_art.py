def _render_frame(frame: List[str], scale: int, bg: Tuple[int, int, int],
                  draw_frame: bool = True, is_boss: bool = False) -> "Image.Image":
    from PIL import Image, ImageDraw, ImageFilter
    h, w = len(frame), len(frame[0])
    pad = 2 if draw_frame else 0
    W, H = (w + pad * 2) * scale, (h + pad * 2) * scale
    # soft vignette bg
    img = Image.new("RGBA", (W, H), bg + (255,))
    px = img.load()
    cx, cy = W / 2, H / 2
    for yy in range(H):
        for xx in range(W):
            dx = (xx - cx) / cx
            dy = (yy - cy) / cy
            fall = min(1.0, (dx * dx + dy * dy) ** 0.5)
            shade = int(18 * fall)
            r = max(0, bg[0] - shade)
            g = max(0, bg[1] - shade)
            b = max(0, bg[2] - shade)
            px[xx, yy] = (r, g, b, 255)

    ox, oy = pad * scale, pad * scale
    for y, row in enumerate(frame):
        for x, ch in enumerate(row):
            col = C.get(ch)
            if not col:
                continue
            x0, y0 = ox + x * scale, oy + y * scale
            for yy in range(y0, y0 + scale):
                for xx in range(x0, x0 + scale):
                    px[xx, yy] = col + (255,)

    # crisp outer frame
    if draw_frame:
        draw = ImageDraw.Draw(img)
        draw.rectangle([0, 0, W - 1, H - 1], outline=(200, 170, 60, 255), width=max(2, scale // 3))
        draw.rectangle([max(1, scale // 4), max(1, scale // 4), W - 1 - max(1, scale // 4), H - 1 - max(1, scale // 4)],
                       outline=(80, 60, 20, 255), width=1)

    # glow pass — slight blur on edges for glow effect
    if is_boss:
        glow = img.filter(ImageFilter.GaussianBlur(radius=scale * 0.4))
        for yy in range(H):
            for xx in range(W):
                g = glow.getpixel((xx, yy))
                if g[3] > 0:
                    o = img.getpixel((xx, yy))
                    r = min(255, o[0] + int(g[0] * 0.15))
                    g_ = min(255, o[1] + int(g[1] * 0.15))
                    b = min(255, o[2] + int(g[2] * 0.15))
                    img.putpixel((xx, yy), (r, g_, b, 255))
    return img


def _render_sprite(key: str, animate: bool = False) -> Optional[bytes]:
    s = SPRITES.get(key)
    if not s:
        return None
    try:
        from PIL import Image
    except ImportError:
        return None
    frames = s["frames"]
    scale = s.get("scale", 4)
    bg = s.get("bg", (16, 18, 24))
    framed = s.get("frame", True)
    if animate and len(frames) >= 2:
        imgs = [_render_frame(f, scale, bg, framed) for f in frames[:2]]
        buf = io.BytesIO()
        imgs[0].save(buf, "GIF", save_all=True, append_images=imgs[1:], duration=500, loop=0, disposal=2)
        return buf.getvalue()
    img = _render_frame(frames[0], scale, bg, framed, s.get("boss", False))
    # upscale with nearest neighbor for extra crispness if small
    if img.width < 200:
        img = img.resize((img.width * 2, img.height * 2), Image.NEAREST)
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def _cache_path(key: str, ext: str) -> str:
    h = hashlib.md5(f"v3_{key}".encode()).hexdigest()[:8]
    return os.path.join(CACHE_DIR, f"v3_{key}_{h}.{ext}")


def get_sprite(key: str, animate: bool = False) -> Optional[bytes]:
    """Return PNG/GIF bytes. Resolves aliases. Caches to disk."""
    if key not in SPRITES:
        key = ALIASES.get(key, key)
    if key not in SPRITES:
        # last resort defaults by rough type keywords
        for cand in ("slime", "goblin", "wooden_sword", "health_potion"):
            if cand in SPRITES:
                key = cand
                break
    if key not in SPRITES:
        return None
    ext = "gif" if animate else "png"
    path = _cache_path(key + ("_ani" if animate else ""), ext)
    if os.path.exists(path) and os.path.getsize(path) > 50:
        with open(path, "rb") as f:
            return f.read()
    data = _render_sprite(key, animate=animate)
    if data:
        try:
            with open(path, "wb") as f:
                f.write(data)
        except Exception:
            pass
    return data


