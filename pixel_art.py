def _grid(rows: List[str]) -> List[str]:
    """Pad/trim rows to equal width."""
    w = max(len(r) for r in rows)
    return [r.ljust(w, ".")[:w] for r in rows]


# ── 32x32 SPRITES ────────────────────────────────────────────
SPRITES: Dict[str, dict] = {}


def _reg(key: str, frames: List[List[str]], scale: int = 4, bg=(16, 18, 24),
         desc_id: str = "", desc_en: str = "", boss: bool = False, frame: bool = True):
    SPRITES[key] = {
        "frames": [_grid(f) for f in frames],
        "scale": scale,
        "bg": bg,
        "desc_id": desc_id,
        "desc_en": desc_en,
        "boss": boss,
        "frame": frame,
    }


